
import streamlit as st
import pandas as pd
import joblib
import os
import matplotlib.pyplot as plt
import seaborn as sns

from sklearn.metrics import (
    accuracy_score,
    roc_auc_score,
    precision_score,
    recall_score,
    f1_score,
    matthews_corrcoef,
    confusion_matrix,
    classification_report
)

# --------------------------------------------------
# 1. Page configuration
# --------------------------------------------------

st.set_page_config(
    page_title="Student Academic Success",
    page_icon="🎓",
    layout="wide"
)

st.title("🎓 Student Academic Success Prediction")
st.subheader("Machine Learning Model Evaluation Dashboard")

st.write(
    "Upload a labelled test dataset, select a trained classifier "
    "and evaluate its prediction performance."
)

st.divider()

# --------------------------------------------------
# 2. Available trained models
# --------------------------------------------------

model_options = {
    "Logistic Regression": "logistic_regression.joblib",
    "Decision Tree": "decision_tree.joblib",
    "KNN": "knn.joblib",
    "Gaussian Naive Bayes": "gaussian_naive_bayes.joblib",
    "SVM": "svm.joblib"
}


@st.cache_resource
def load_model(model_path):
    return joblib.load(model_path)


# --------------------------------------------------
# 3. Model selection
# --------------------------------------------------

st.subheader("Select Classifier")

selected_model = st.selectbox(
    "Choose a machine learning model:",
    list(model_options.keys())
)

model_file = os.path.join(
    "model",
    model_options[selected_model]
)

if not os.path.exists(model_file):
    st.error(f"Model file not found: {model_file}")
    st.stop()

pipeline = load_model(model_file)

# --------------------------------------------------
# 4. Upload test dataset
# --------------------------------------------------

st.divider()
st.subheader("Upload Test Dataset")

uploaded_file = st.file_uploader(
    "Upload a CSV file containing input features and Target",
    type=["csv"]
)

if uploaded_file is not None:

    try:
        # Dataset generated by our training script uses ;
        test_df = pd.read_csv(uploaded_file, sep=";")

        # Fallback for comma-separated CSV files
        if test_df.shape[1] == 1:
            uploaded_file.seek(0)
            test_df = pd.read_csv(uploaded_file, sep=",")

        test_df.columns = test_df.columns.str.strip()

        # Check target column
        if "Target" not in test_df.columns:
            st.error(
                "The uploaded CSV must contain a 'Target' column."
            )
            st.stop()

        # Separate features and actual target
        X_test = test_df.drop(columns=["Target"])
        y_test = test_df["Target"]

        # Validate input features against the trained model
        expected_columns = list(pipeline.feature_names_in_)

        missing_columns = [
            col for col in expected_columns
            if col not in X_test.columns
        ]

        extra_columns = [
            col for col in X_test.columns
            if col not in expected_columns
        ]

        if missing_columns or extra_columns:
            st.error("The uploaded dataset does not match the training features.")

            if missing_columns:
                st.write("Missing columns:", missing_columns)

            if extra_columns:
                st.write("Unexpected columns:", extra_columns)

            st.stop()

        # Ensure the same feature order used during training
        X_test = X_test[expected_columns]

        if X_test.empty:
            st.error("The uploaded dataset contains no records.")
            st.stop()

        if y_test.isnull().any():
            st.error("The Target column contains missing values.")
            st.stop()

        # --------------------------------------------------
        # 5. Generate predictions
        # --------------------------------------------------

        y_pred = pipeline.predict(X_test)
        y_prob = pipeline.predict_proba(X_test)

        model_classes = pipeline.classes_

        if not set(y_test.unique()).issubset(set(model_classes)):
            st.error(
                "The Target column contains classes not recognised "
                "by the selected trained model."
            )
            st.stop()

        # --------------------------------------------------
        # 6. Calculate evaluation metrics
        # --------------------------------------------------

        accuracy = accuracy_score(y_test, y_pred)

        auc = roc_auc_score(
            y_test,
            y_prob,
            labels=model_classes,
            multi_class="ovr",
            average="macro"
        )

        precision = precision_score(
            y_test,
            y_pred,
            average="macro",
            zero_division=0
        )

        recall = recall_score(
            y_test,
            y_pred,
            average="macro",
            zero_division=0
        )

        f1 = f1_score(
            y_test,
            y_pred,
            average="macro",
            zero_division=0
        )

        mcc = matthews_corrcoef(y_test, y_pred)

        # --------------------------------------------------
        # 7. Display evaluation metrics
        # --------------------------------------------------

        st.divider()
        st.subheader("Model Evaluation Results")

        st.write("**Selected Model:**", selected_model)
        st.write("**Number of Test Records:**", len(X_test))

        col1, col2, col3 = st.columns(3)

        col1.metric("Accuracy", f"{accuracy:.4f}")
        col2.metric("AUC", f"{auc:.4f}")
        col3.metric("Precision", f"{precision:.4f}")

        col4, col5, col6 = st.columns(3)

        col4.metric("Recall", f"{recall:.4f}")
        col5.metric("F1 Score", f"{f1:.4f}")
        col6.metric("MCC", f"{mcc:.4f}")

        # --------------------------------------------------
        # 8. Confusion matrix
        # --------------------------------------------------

        st.divider()
        st.subheader("Confusion Matrix")

        cm = confusion_matrix(
            y_test,
            y_pred,
            labels=model_classes
        )

        fig, ax = plt.subplots(figsize=(8, 5))

        sns.heatmap(
            cm,
            annot=True,
            fmt="d",
            cmap="Blues",
            xticklabels=model_classes,
            yticklabels=model_classes,
            ax=ax
        )

        ax.set_xlabel("Predicted Class")
        ax.set_ylabel("Actual Class")
        ax.set_title(f"{selected_model} - Confusion Matrix")

        st.pyplot(fig)
        plt.close(fig)

        # --------------------------------------------------
        # 9. Classification report
        # --------------------------------------------------

        st.divider()
        st.subheader("Classification Report")

        report = classification_report(
            y_test,
            y_pred,
            output_dict=True,
            zero_division=0
        )

        report_df = pd.DataFrame(report).transpose()

        st.dataframe(
            report_df.round(4),
            use_container_width=True
        )

        # --------------------------------------------------
        # 10. Dataset preview
        # --------------------------------------------------

        st.divider()
        st.subheader("Uploaded Dataset Preview")

        st.dataframe(
            test_df.head(10),
            use_container_width=True
        )

        st.success("Model evaluation completed successfully!")

    except Exception as e:
        st.error(f"Unable to process the uploaded dataset: {e}")

else:
    st.info("Please upload your labelled test CSV file to begin evaluation.")
